// types.h

// Define u8 as an unsigned 8-bit integer with a range of 0 to 255.
typedef unsigned char u8;

// Define s8 as a signed 8-bit integer with a range of -128 to 127.
typedef signed char s8;

// Define u16 as an unsigned 16-bit integer with a range of 0 to 65535.
typedef unsigned short u16;

// Define s16 as a signed 16-bit integer with a range of -32768 to 32767.
typedef short s16;

// Define u32 as an unsigned 32-bit integer used for addresses, counters, and amounts.
typedef unsigned int u32;

// Define s32 as a signed 32-bit integer used for positive and negative values.
typedef int s32;

// Define f32 as a 32-bit floating-point type for decimal calculations.
typedef float f32;

// Define f64 as a 64-bit floating-point type for higher-precision decimal calculations.
typedef double f64;
